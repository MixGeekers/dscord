// Writes the keyframes of the loading animation (ui/loading.tsx) into ui/styles.css, between the two marker comments.
// The whale swims a half circle around the bubble; the bubble blinks over to where the whale was; the whale swims into
// the bubble's old place. The second half does the same the other way round, so every loop ends on the mark as drawn.
// Both pairs of eyes keep looking at the other shape. Paths are sampled and written as linear keyframes.
// Run `node scripts/loading-motion.mjs` after changing anything below.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const stylesheet = path.join(root, 'ui/styles.css');
const BEGIN = '/* loading-motion:begin (generated by scripts/loading-motion.mjs) */';
const END = '/* loading-motion:end */';

// Centres of the two shapes and their eyes, in percent of the mark's square (see ui/loading-*.png).
const WHALE = [45.07, 37.97];
const HUMAN = [65.27, 72.43];
const ORBIT = 58; // radius of the swim around the bubble, in percent of the mark
const SWIM_SCALE = 0.5; // the whale makes itself small to swim
/** Half way through the loop the whale rests beyond the bubble's old place, a little smaller, so the two do not overlap. */
const AWAY = [HUMAN[0] + (HUMAN[0] - WHALE[0]) * 0.5, HUMAN[1] + (HUMAN[1] - WHALE[1]) * 0.5];
const AWAY_SCALE = 0.8;
const LOOK = 5; // how far the eyes move toward the other shape, in percent of the mark as drawn
/** Eyes close for a moment: the bubble just after it pops in, the whale once it has landed (times within a half). */
const blink = (v, at) => { const t = span(v, at, at + 0.05); return t > 0 && t < 1 ? 1 - 0.9 * Math.sin(t * Math.PI) : 1; };

const clamp = (value, low = 0, high = 1) => Math.min(high, Math.max(low, value));
const span = (value, from, to) => clamp((value - from) / (to - from));
const smooth = t => t * t * (3 - 2 * t);
const lerp = (a, b, t) => a + (b - a) * t;
const add = (a, b) => [a[0] + b[0], a[1] + b[1]];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1]];
const times = (a, k) => [a[0] * k, a[1] * k];
const length = a => Math.hypot(a[0], a[1]);
const unit = a => times(a, 1 / (length(a) || 1));
/** Overshooting ease for pops: 0 → ~1.12 → 1. */
const spring = t => (t <= 0 ? 0 : t >= 1 ? 1 : 1 - Math.cos(t * Math.PI * 2.6) * Math.exp(-5.2 * t));

/** Where everything is at time v of one half: the whale swims from `start` round the bubble at `pivot` to `end`,
 * and the bubble blinks over to `home`. */
function half(v, { start, startScale, pivot, home, end, endScale }) {
  const out = sub(start, pivot);
  const angle0 = Math.atan2(out[1], out[0]);
  const ring = angle => add(pivot, times([Math.cos(angle), Math.sin(angle)], ORBIT));
  // Whale: lift off onto the ring, swim half way round, dive into the bubble's old place.
  let whale; let scale; let swimming = 0;
  if (v < 0.06) { whale = start; scale = startScale; }
  else if (v < 0.18) { const t = smooth(span(v, 0.06, 0.18)); whale = add(pivot, times(unit(out), lerp(length(out), ORBIT, t))); scale = lerp(startScale, SWIM_SCALE, t); swimming = t; }
  else if (v < 0.6) { const t = smooth(span(v, 0.18, 0.6)); whale = ring(angle0 + Math.PI * t); scale = SWIM_SCALE; swimming = 1; }
  else if (v < 0.78) { const t = smooth(span(v, 0.6, 0.78)); whale = lerp2(ring(angle0 + Math.PI), end, t); scale = lerp(SWIM_SCALE, endScale, t); swimming = 1 - t; }
  else { whale = end; scale = endScale; }
  // Landing squash once the whale is in.
  const land = span(v, 0.78, 0.96);
  const squash = land > 0 && land < 1 ? Math.sin(land * Math.PI * 2) * Math.exp(-3 * land) * 0.16 : 0;
  // Bubble: crouch, blink out, pop in where the whale started.
  let bubble = pivot; let bubbleScale = [1, 1]; let bubbleVisible = 1;
  if (v >= 0.5 && v < 0.56) { const t = Math.sin(span(v, 0.5, 0.56) * Math.PI); bubbleScale = [1 + 0.14 * t, 1 - 0.16 * t]; }
  else if (v >= 0.56 && v < 0.6) { const t = span(v, 0.56, 0.6); bubbleScale = [1 - t, 1 - t]; bubbleVisible = 1 - t; }
  else if (v >= 0.6) { bubble = home; const t = spring(span(v, 0.6, 0.74)); bubbleScale = [t, t]; bubbleVisible = clamp(t * 3); }
  return { whale, scale, swimming, squash, bubble, bubbleScale, bubbleVisible };
}
const lerp2 = (a, b, t) => [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];

/** One loop: whale from its own place round the bubble, then back. */
function frame(u) {
  const first = u < 0.5;
  const state = first
    ? half(u * 2, { start: WHALE, startScale: 1, pivot: HUMAN, home: WHALE, end: AWAY, endScale: AWAY_SCALE })
    : half(u * 2 - 1, { start: AWAY, startScale: AWAY_SCALE, pivot: WHALE, home: HUMAN, end: WHALE, endScale: 1 });
  const v = first ? u * 2 : u * 2 - 1;
  return { ...state, u, whaleBlink: blink(v, 0.9), humanBlink: blink(v, 0.76) };
}

const STEPS = 400;
const frames = Array.from({ length: STEPS + 1 }, (_, index) => frame(index / STEPS));

// The whale faces the way it swims (it is drawn facing left), smoothed so that it turns rather than flips.
const raw = frames.map((current, index) => {
  const next = frames[Math.min(STEPS, index + 2)]; const previous = frames[Math.max(0, index - 2)];
  const vx = next.whale[0] - previous.whale[0];
  return Math.abs(vx) < 0.05 ? null : vx > 0 ? -1 : 1;
});
let facing = 1;
const target = raw.map(value => (facing = value ?? facing));
// It turns back to face left before it swims into place, so it never turns round right next to the bubble.
frames.forEach((f, index) => { const v = (f.u * 2) % 1; if (v < 0.1 || v > 0.56) target[index] = 1; });
const WINDOW = 6;
const faced = target.map((_, index) => {
  let sum = 0; let count = 0;
  for (let k = index - WINDOW; k <= index + WINDOW; k++) { sum += target[(k + STEPS) % STEPS]; count++; }
  return sum / count;
});

const round = value => Number(value.toFixed(2)).toString().replace(/^(-?)0\./, '$1.');
const pct = value => `${round(value)}%`;

function tracks() {
  const whale = []; const whaleEyes = []; const human = []; const humanEyes = [];
  frames.forEach((f, index) => {
    const wag = f.swimming * Math.sin(f.u * Math.PI * 2 * 7) * 9;
    const flip = faced[index];
    const [dx, dy] = sub(f.whale, WHALE);
    whale.push([f.u, `translate(${pct(dx)}, ${pct(dy)}) rotate(${round(wag)}deg) scale(${round(flip * f.scale * (1 + f.squash))}, ${round(f.scale * (1 - f.squash))})`]);
    // The whale's eyes move inside the whale, which is drawn smaller while it swims; keep the glance the same size.
    const towardHuman = times(unit(sub(f.bubble, f.whale)), Math.min(LOOK / f.scale, LOOK * 1.4));
    whaleEyes.push([f.u, `translate(${pct(towardHuman[0] * Math.sign(flip || 1))}, ${pct(towardHuman[1])}) scale(1, ${round(f.whaleBlink)})`]);
    const [bx, by] = sub(f.bubble, HUMAN);
    human.push([f.u, `translate(${pct(bx)}, ${pct(by)}) scale(${round(f.bubbleScale[0])}, ${round(f.bubbleScale[1])})`, round(f.bubbleVisible)]);
    const towardWhale = times(unit(sub(f.whale, f.bubble)), LOOK);
    humanEyes.push([f.u, `translate(${pct(towardWhale[0])}, ${pct(towardWhale[1])}) scale(1, ${round(f.humanBlink)})`]);
  });
  return { whale, whaleEyes, human, humanEyes };
}

/** Drops stops whose values are the linear blend of their neighbours, so the stylesheet stays small. */
function simplify(track) {
  const numbers = entry => entry.slice(1).join(' ').match(/-?\.?\d+(?:\.\d+)?/g).map(Number);
  const values = track.map(numbers);
  const fits = (from, to) => {
    for (let index = from + 1; index < to; index++) {
      const t = (track[index][0] - track[from][0]) / (track[to][0] - track[from][0]);
      if (values[index].some((value, k) => Math.abs(lerp(values[from][k], values[to][k], t) - value) > 0.12)) return false;
    }
    return true;
  };
  const kept = [0];
  let from = 0;
  while (from < track.length - 1) {
    let to = from + 1;
    while (to + 1 < track.length && fits(from, to + 1)) to++;
    kept.push(to);
    from = to;
  }
  return kept.map(index => track[index]);
}

function keyframes(name, track, opacity = false) {
  const stops = simplify(track).map(([u, transform, visible]) => `  ${pct(u * 100)} { transform: ${transform};${opacity ? ` opacity: ${visible};` : ''} }`);
  return `@keyframes ${name} {\n${stops.join('\n')}\n}`;
}

export function loadingMotion() {
  const { whale, whaleEyes, human, humanEyes } = tracks();
  return [
    BEGIN,
    keyframes('ds-loading-whale', whale),
    keyframes('ds-loading-whale-eyes', whaleEyes),
    keyframes('ds-loading-human', human, true),
    keyframes('ds-loading-human-eyes', humanEyes),
    END,
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = await readFile(stylesheet, 'utf8');
  const from = css.indexOf(BEGIN); const to = css.indexOf(END);
  if (from < 0 || to < 0) throw new Error('ui/styles.css has no loading-motion markers');
  await writeFile(stylesheet, css.slice(0, from) + loadingMotion() + css.slice(to + END.length));
  console.log('ui/styles.css loading keyframes written');
}
